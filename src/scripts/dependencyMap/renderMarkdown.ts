import { type DependencyMap, transitiveDependents } from "./buildMap.js";

/** `@aurodesignsystem/auro-button` → `auro-button`. */
export function shortName(pkg: string): string {
  return pkg.replace(/^@[^/]+\//, "");
}

function nodeId(pkg: string): string {
  return shortName(pkg).replace(/[^a-zA-Z0-9]/g, "_");
}

/**
 * Mermaid flowchart of the bundle graph. Arrows point in the direction a
 * release flows: `auro-icon --> auro-dialog` means auro-dialog bundles
 * auro-icon, so an auro-icon release must cascade into auro-dialog. Dotted
 * arrows are `extends` edges (class compiled in without a versioned tag).
 */
export function renderMermaid(map: DependencyMap): string {
  const lines = ["graph LR"];
  for (const name of Object.keys(map.packages)) {
    lines.push(`  ${nodeId(name)}["${shortName(name)}"]`);
  }
  for (const [consumer, node] of Object.entries(map.packages)) {
    for (const edge of node.bundles) {
      const arrow = edge.kind === "extends" ? "-.->" : "-->";
      lines.push(`  ${nodeId(edge.package)} ${arrow} ${nodeId(consumer)}`);
    }
  }
  return lines.join("\n");
}

function list(items: string[]): string {
  return items.length > 0
    ? items.map((item) => `\`${shortName(item)}\``).join(", ")
    : "—";
}

/**
 * Human- and AI-readable rendering of the dependency map: what the graph
 * means, a Mermaid diagram, a per-package table with direct and transitive
 * consumers, the release order, and any drift warnings.
 */
export function renderDependencyMapMarkdown(map: DependencyMap): string {
  const rows = Object.entries(map.packages).map(([name, node]) => {
    const bundles = node.bundles.map((edge) => {
      const version = edge.pinned ? `@${edge.pinned}` : "";
      const kind = edge.kind === "extends" ? " (extends)" : "";
      const stale = edge.stale ? ` ⚠ stale (range ${edge.range})` : "";
      return `\`${shortName(edge.package)}${version}\`${kind}${stale}`;
    });
    const downstream = transitiveDependents(map, name).flat();
    return `| \`${name}\` | ${bundles.join(", ") || "—"} | ${list(node.bundledBy)} | ${list(downstream)} |`;
  });

  const internal = Object.entries(map.packages)
    .filter(([, node]) => node.internal)
    .map(([name, node]) => {
      const entries = Object.entries(node.internal!).map(
        ([component, deps]) => `- \`${shortName(component)}\` → ${list(deps)}`,
      );
      return `### \`${name}\` (internal, same release)\n\n${entries.join("\n")}`;
    });

  const batches = map.releaseOrder.map(
    (batch, index) => `${index + 1}. ${list(batch)}`,
  );

  return [
    "# Auro component dependency map",
    "",
    `> Generated by \`auro deps map\` on ${map.generatedAt} (schema v${map.schemaVersion}). Do not edit by hand — regenerate it.`,
    "",
    "## How to read this",
    "",
    "Auro components **bundle** other Auro components into their own build. They register them under a version-suffixed tag via `AuroDependencyVersioning.generateTag`, or subclass them directly. The sub-component is compiled in, so its releases reach users only when each consumer bumps the devDependency, rebuilds (`npm run build:version` refreshes `src/<name>Version.js`), and cuts its own release.",
    "",
    "- **Bundles**: sub-components this package compiles in, with the version pinned at its last build. `(extends)` = class imported without a versioned tag. `⚠ stale` = the committed version file is outside the package.json range, so the tag name no longer matches the code compiled in.",
    "- **Bundled by**: packages that directly bundle this one.",
    "- **All downstream**: every package that must rebuild and release after this one releases, in release order.",
    "- **Patch/minor** releases of a package should cascade into everything downstream. **Major** releases need a manual migration.",
    "",
    "## Diagram",
    "",
    "Arrows point the way a release flows (`auro-icon --> auro-dialog`: auro-dialog bundles auro-icon). Dotted arrows are `extends` edges.",
    "",
    "```mermaid",
    renderMermaid(map),
    "```",
    "",
    "## Packages",
    "",
    "| Package | Bundles | Bundled by | All downstream |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
    ...(internal.length > 0
      ? ["## Monorepo internals", "", ...internal, ""]
      : []),
    "## Release order",
    "",
    "Each batch bundles only packages from earlier batches. Release top to bottom.",
    "",
    ...batches,
    "",
    ...(map.warnings.length > 0
      ? ["## Warnings", "", ...map.warnings.map((w) => `- ${w}`), ""]
      : []),
  ].join("\n");
}
