// Builds <genDir>/<tag>.figma.ts deterministically (no AI, no network, no timestamps) from the rules in binding-rule.md.
//
// Flags: [--check] [--validate]
// One figma.connect group is written for every Figma component set of the component (one Figma URL each).
// Inputs (paths come from ctx, see binding-core.mjs): the CEM map, <tag>.translate.md, the saved Figma snapshots, and package.json / CHANGELOG.md of sourceDir.
// The Figma URLs come from the Figma connector config (figma-connector.config.ts), via ctx.figmaNodes.
//
// --check writes nothing; it exits 1 if the generated <tag>.figma.ts differs from what would be built.
// --validate builds in memory and writes nothing: it checks that the inputs are consistent, so CI can run it without a generated file on disk.
// Exit codes: 0 ok, 1 stale (--check only), 2 bad input or inconsistent translate file.
// The mismatch file (what is and is not addressed) is a separate script: build-mismatch.mjs.
import fs from "node:fs";
import path from "node:path";
import { guard, loadComponent } from "./binding-core.mjs";

export function run(argv, runCtx) {
  return guard("build-figma", () => {
    const {
      args,
      q,
      readText,
      readJson,
      fail,
      warnings,
      translatePath,
      cemMapPath,
      packagePath,
      changelogPath,
      genDir,
      map,
      nodes,
      bound,
      stateBlocks,
    } = loadComponent("build-figma", argv, runCtx, ["check", "validate"]);

    // ---------- version header ----------
    const pkg = readJson(packagePath);
    let codeVersion = pkg.version;
    let versionSource = "";
    if (!codeVersion || /^0\.0\.0/.test(codeVersion)) {
      const cl = readText(changelogPath).match(
        /^#{1,2}\s+\[?(\d+\.\d+\.\d+[\w.-]*)\]?(?:\([^)]*\))?\s+\((\d{4}-\d{2}-\d{2})\)/m,
      );
      if (!cl) fail(`no version found in ${changelogPath}`);
      codeVersion = cl[1];
      versionSource = `latest CHANGELOG entry, ${cl[2]}; `;
    }
    for (const n of nodes)
      for (const k of ["version", "lastModified", "name"])
        if (!n.figmaJson[k])
          fail(`Figma data for node ${n.nodeId} has no "${k}"`);

    // ---------- .figma.ts ----------
    const RESERVED = new Set([
      "default",
      "class",
      "function",
      "new",
      "delete",
      "var",
      "let",
      "const",
      "return",
      "switch",
      "case",
      "in",
      "of",
      "if",
      "else",
      "for",
      "while",
      "do",
      "this",
      "null",
      "true",
      "false",
      "void",
      "typeof",
      "with",
      "yield",
      "import",
      "export",
      "enum",
      "await",
    ]);
    let blockCount = 0;
    const out = [
      `// Based on: ${pkg.name} ${codeVersion} (${versionSource}CEM from origin/main)`,
      ...nodes.map(
        (n) =>
          `//           Figma "${n.figmaJson.name}" file version ${n.figmaJson.version}, last modified ${n.figmaJson.lastModified} (${n.doc.name} component set, node ${n.nodeId})`,
      ),
      `import figma, { html } from '@figma/code-connect/html'`,
      "",
      `// Generated by build-figma.mjs from ${path.basename(cemMapPath)}, ${path.basename(translatePath)} and the Figma property definitions. Do not edit by hand.`,
      `// Rules: binding-rule.md. What is not bound: ${map.tag}.mismatch.md.`,
      "",
    ];
    for (const n of nodes) {
      const nodeBound = bound.filter((x) => x.nodeId === n.nodeId);
      const nodeStates = stateBlocks.filter((b) => b.nodeId === n.nodeId);
      if (!nodeBound.length && !nodeStates.length)
        warnings.push(
          `${n.doc.name} (node ${n.nodeId}) has no bindings: no property matches a CEM attribute or slot and translate.md has no row for it`,
        );
      for (const b of nodeStates.length
        ? nodeStates
        : [{ prop: null, option: null, attr: null }]) {
        blockCount++;
        const propLines = [];
        const argNames = [];
        const tagAttrs = [];
        const children = [];
        if (b.attr) tagAttrs.push(b.attr);
        for (const x of nodeBound) {
          if (x.kind === "enum") {
            const vals = Object.entries(x.pairs)
              .map(
                ([o, v]) =>
                  `      ${q(o)}: ${q(x.complete ? v : `${x.attr}="${v}"`)},`,
              )
              .join("\n");
            propLines.push(
              `    ${x.key}: figma.enum(${q(x.figma)}, {\n${vals}\n    }),`,
            );
            argNames.push(x.key);
            tagAttrs.push(
              x.complete ? `${x.attr}="\${${x.key}}"` : `\${${x.key}}`,
            );
          } else if (x.kind === "boolean") {
            propLines.push(
              `    ${x.attr}: figma.boolean(${q(x.figma)}, { true: ${q(x.attr)}, false: undefined }),`,
            );
            argNames.push(x.attr);
            tagAttrs.push(`\${${x.attr}}`);
          } else {
            let v = x.slot.replace(/[^a-zA-Z0-9]/g, "");
            if (!v || /^\d/.test(v) || RESERVED.has(v) || argNames.includes(v))
              v = `slot${v.charAt(0).toUpperCase()}${v.slice(1)}`;
            while (argNames.includes(v)) v += "_";
            propLines.push(`    ${v}: figma.string(${q(x.figma)}),`);
            argNames.push(v);
            children.push(`<span slot="${x.slot}">\${${v}}</span>`);
          }
        }
        const open = `${[`<${map.tag}`, ...tagAttrs].join(" ")}>`;
        const body = children.length
          ? `    ${open}\n${children.map((c) => `      ${c}`).join("\n")}\n    </${map.tag}>`
          : `    ${open}</${map.tag}>`;
        out.push(
          `// ${b.prop ? `${n.doc.name} / ${b.prop}=${b.option}` : n.doc.name}`,
          `figma.connect(${q(`${n.base}?node-id=${n.dashed}`)}, {`,
          ...(b.prop ? [`  variant: { ${q(b.prop)}: ${q(b.option)} },`] : []),
          "  props: {",
          ...propLines,
          "  },",
          `  example: ({ ${argNames.join(", ")} }) => html\``,
          body,
          "  `,",
          "})",
          "",
        );
      }
    }

    const result = out.join("\n");
    const outFile = path.join(genDir, `${map.tag}.figma.ts`);

    for (const w of warnings) console.error(`build-figma: warning: ${w}`);
    if (args.validate) {
      console.log(
        `${map.tag}: figma.ts can be built (${bound.length} bindings, ${blockCount} blocks)`,
      );
      return 0;
    }
    const current = fs.existsSync(outFile)
      ? fs.readFileSync(outFile, "utf8")
      : null;
    if (args.check) {
      if (current === result) {
        console.log(`${map.tag}: ${outFile} is up to date`);
        return 0;
      }
      console.error(
        `${map.tag}: ${outFile} is ${current === null ? "missing" : "stale"}. Run \`auro docs --figma\`.`,
      );
      return 1;
    }
    fs.mkdirSync(genDir, { recursive: true });
    if (current !== result) fs.writeFileSync(outFile, result);
    console.log(
      `${map.tag}: ${path.basename(outFile)} ${current === result ? "unchanged" : "written"} (${bound.length} bindings, ${blockCount} blocks${nodes.length > 1 ? `, ${nodes.length} component sets` : ""})`,
    );
  });
}
